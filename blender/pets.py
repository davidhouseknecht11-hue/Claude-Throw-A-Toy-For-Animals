# Throw a Toy pets in the classic Roblox brick-pet style. Z up, facing +Y, ground z=0, units = studs.
# Bones: body, head, earL/R, legFL/FR/BL/BR, armL/R, wingL/R, tail. In mirror calls (.m) give the +X (right) bone.
from brick import Brick, legs4

INK, HI = "141418", "FFFFFF"


def eyes(a, x, y, z, w=0.13, h=0.17, color=INK, bone="head", glow=False):
    a.m((w, 0.06, h), (x, y + 0.02, z), color, bone, kind="neon" if glow else "plastic")
    if not glow:
        a.m((w * 0.42, 0.07, h * 0.36), (x - w * 0.18, y + 0.03, z + h * 0.24), HI, bone, kind="neon")


def side_eyes(a, x, y, z, s=0.14, bone="head"):
    a.m((0.06, s, s), (x + 0.02, y, z), INK, bone)
    a.m((0.07, s * 0.4, s * 0.38), (x + 0.03, y + s * 0.2, z + s * 0.22), HI, bone, kind="neon")


